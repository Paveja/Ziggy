import { test, expect } from "playwright/test";
const baseURL = process.env.BASE_URL;
test.use({ baseURL });
test.afterEach(async ({ page }) => {
  if (process.env.QA_VIDEO === "1") await page.waitForTimeout(1500);
});
test("D13 discovery pagination persistence and filter reset journey", async ({ page }) => {
  const titles = page.getByRole("region", { name: "Restaurants", exact: true }).getByRole("article").getByRole("heading", { level: 2 });
  await page.goto("/");
  await page.getByRole("searchbox").fill("");
  await page.getByRole("combobox", { name: "Cuisine", exact: true }).selectOption("");
  await page.getByRole("combobox", { name: "Sort by" }).selectOption("price");
  await page.getByRole("button", { name: "Discover", exact: true }).click();
  await expect(titles.first()).toHaveText("Cocoa Corner");
  const first = await titles.allTextContents();
  await page.getByRole("link", { name: "Next", exact: true }).click();
  await expect(titles).toHaveText(["Basil & Brick", "Miso Moon", "The Dough House"]);
  await expect(page).toHaveURL(url => url.searchParams.get("page") === "2" && url.searchParams.get("sort") === "price" && url.searchParams.get("q") === "" && url.searchParams.get("cuisine") === "");
  expect(first.filter(name => ["Basil & Brick", "Miso Moon", "The Dough House"].includes(name))).toEqual([]);
  await page.reload();
  await expect(titles).toHaveText(["Basil & Brick", "Miso Moon", "The Dough House"]);
  await expect(page.getByRole("combobox", { name: "Sort by" })).toHaveValue("price");
  await page.getByRole("link", { name: "Previous", exact: true }).click();
  await expect(titles).toHaveText(first);
  await page.getByRole("link", { name: "Next", exact: true }).click();
  await expect(titles).toHaveCount(3);
  await page.getByRole("searchbox").fill("pizza");
  await page.getByRole("combobox", { name: "Cuisine", exact: true }).selectOption("Italian");
  await page.getByRole("combobox", { name: "Sort by" }).selectOption("delivery");
  await page.getByRole("button", { name: "Discover", exact: true }).click();
  await expect(titles).toHaveText(["The Dough House"]);
  await expect(page).toHaveURL(url => !url.searchParams.has("page") && url.searchParams.get("cuisine") === "Italian" && url.searchParams.get("q") === "pizza");
  await page.reload();
  await expect(page.getByRole("searchbox")).toHaveValue("pizza");
  await expect(page.getByRole("combobox", { name: "Cuisine", exact: true })).toHaveValue("Italian");
  await expect(page.getByRole("combobox", { name: "Sort by" })).toHaveValue("delivery");
  await page.getByRole("link", { name: "Clear filters" }).click();
  await expect(page).toHaveURL("/");
  await expect(titles).toHaveCount(9);
  await expect(titles.first()).toHaveText("Sugar Lane");
  await expect(page.getByRole("searchbox")).toHaveValue("");
  await expect(page.getByRole("combobox", { name: "Cuisine", exact: true })).toHaveValue("");
  await expect(page.getByRole("combobox", { name: "Sort by" })).toHaveValue("rating");
});
